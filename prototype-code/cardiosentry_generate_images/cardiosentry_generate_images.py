LOGS = WORK/'logs'; LOGS.mkdir(parents=True, exist_ok=True)

def run(script, *args, env=None, quiet=False, tag=None):
    """Run a pipeline stage, STREAMING its output live and teeing it to a log.

    Not subprocess.run(capture_output=True): that buffers everything until the
    process exits, so a 5-8 hour stage 3 would show nothing at all until it was
    over. Popen + line iteration prints progress as it happens, and -u stops
    Python block-buffering its stdout when writing to a pipe instead of a tty.

    Every line also lands in WORK/logs/<stage>.log, so the Colab terminal can
        tail -f /content/work/logs/stage3.log
    and watch the same output from outside the notebook.
    """
    name = tag or script.replace('.py','')
    log  = LOGS/f'{name}.log'
    cmd  = [sys.executable, '-u', script, *args]
    started = time.time()
    lines = []
    with open(log, 'w') as fh:
        proc = subprocess.Popen(cmd, cwd=PIPE, env={**os.environ, **(env or {})},
                                stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                text=True, bufsize=1)
        for line in proc.stdout:
            fh.write(line); fh.flush()
            lines.append(line)
            if not quiet:
                print(line, end='', flush=True)
        proc.wait()
    out = ''.join(lines).strip()
    mins = (time.time()-started)/60
    print(f'  [{name}] finished in {mins:.1f} min  ->  {log}')
    if proc.returncode:
        print(out[-2000:]); raise SystemExit(f'{script} failed (see {log})')
    return out

