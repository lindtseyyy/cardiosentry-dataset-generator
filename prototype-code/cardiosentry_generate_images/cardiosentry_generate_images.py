import threading
stop, freed2 = threading.Event(), [0, 0]

def reap():
    pending = {r for r in dsts if srcs[r].with_suffix('.json').exists()}
    while pending and not stop.is_set():
        for rec in list(pending):
            if all(p.exists() and p.with_suffix('.json').exists() for p in dsts[rec]):
                jp = srcs[rec].with_suffix('.json')
                if jp.exists():
                    freed2[0] += jp.stat().st_size; freed2[1] += 1; jp.unlink()
                pending.discard(rec)
        stop.wait(60)

