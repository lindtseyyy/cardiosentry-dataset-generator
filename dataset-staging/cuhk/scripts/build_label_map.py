"""
CardioSentry / CUHK-STEMI staging -- build the explicit label mapping.

Applies the ordered rule table in config/cuhk_code_rules.yaml to every
Philips statement code found by scan_xml_index.py, and writes:

  config/label_map_cuhk.yaml   a `sources: cuhk_stemi:` block in EXACTLY the
                               schema of the main pipeline's
                               config/label_mapping.yaml -- one explicit entry
                               per code, ready to paste in at merge time.
  reports/code_decisions.csv   every code, how many records carry it, which
                               rule caught it, the resulting status, and the
                               algorithm's own statement text. This is the
                               table to hand a clinician for review.

No label decision is made in this file; the decisions live in the rules YAML.
"""
from __future__ import annotations

import csv
import html
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
RULES_YAML = ROOT / "config" / "cuhk_code_rules.yaml"
CODES_CSV = ROOT / "data" / "index" / "code_inventory.csv"
OUT_YAML = ROOT / "config" / "label_map_cuhk.yaml"
OUT_CSV = ROOT / "reports" / "code_decisions.csv"


def norm(text: str) -> str:
    """Statement text as the rules see it: unescaped, collapsed, lower-case."""
    return re.sub(r"\s+", " ", html.unescape(text or "")).strip().lower()


def classify(text: str, buckets: list) -> dict:
    for b in buckets:
        if re.search(b["match"], text):
            return b
    raise RuntimeError("rule table has no catch-all bucket")


def block_scalar(text: str, indent: str) -> str:
    """Render `reason` as a folded YAML block, wrapped at ~72 columns."""
    words, lines, cur = " ".join(str(text).split()).split(" "), [], ""
    for w in words:
        if len(cur) + len(w) + 1 > 72:
            lines.append(cur)
            cur = w
        else:
            cur = f"{cur} {w}".strip()
    if cur:
        lines.append(cur)
    return "\n".join(indent + ln for ln in lines)


def main() -> int:
    rules = yaml.safe_load(RULES_YAML.read_text(encoding="utf-8"))
    buckets = rules["buckets"]
    for b in buckets:
        b["_rx"] = re.compile(b["match"])

    if not CODES_CSV.exists():
        print(f"missing {CODES_CSV} -- run scripts/scan_xml_index.py first",
              file=sys.stderr)
        return 1

    rows = list(csv.DictReader(CODES_CSV.open(encoding="utf-8")))
    rows.sort(key=lambda r: -int(r["n_records"]))

    decisions = []
    for r in rows:
        code = r["philips_code"]
        if code == "?":
            continue
        text = norm(r["example_statement"])
        b = next(bb for bb in buckets if bb["_rx"].search(text))
        decisions.append({
            "philips_code": code,
            "n_records": int(r["n_records"]),
            "pct_of_records": r["pct_of_records"],
            "rule_bucket": b["name"],
            "status": b["status"],
            "maps_to": b.get("maps_to") or "",
            "disqualifies_normal": str(bool(
                b.get("disqualifies_normal", b["status"] == "ACCEPT"))).lower(),
            "philips_statement": re.sub(r"\s+", " ", html.unescape(
                r["example_statement"])).strip(),
        })

    OUT_CSV.parent.mkdir(parents=True, exist_ok=True)
    with OUT_CSV.open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(decisions[0].keys()))
        w.writeheader()
        w.writerows(decisions)

    # ---- emit the pipeline-schema YAML -------------------------------
    by_bucket: dict[str, list] = {}
    for d in decisions:
        by_bucket.setdefault(d["rule_bucket"], []).append(d)

    out = [
        "# =====================================================================",
        "# CardioSentry -- CUHK STEMI XML: EXPLICIT LABEL MAPPING",
        "# =====================================================================",
        "# GENERATED by scripts/build_label_map.py from",
        "#   config/cuhk_code_rules.yaml + data/index/code_inventory.csv",
        "# Do not hand-edit: edit the rule table and regenerate.",
        "#",
        "# Schema is identical to the main pipeline's config/label_mapping.yaml,",
        "# so at merge time this `cuhk_stemi:` block can be pasted under that",
        "# file's `sources:` key unchanged.",
        "#",
        "# PROVENANCE WARNING. Unlike PTB-XL (human-overread) and the 2026 ACS",
        "# STEMI dataset (dedicated clinician-assigned STEMI column), every label",
        "# below is derived from the Philips DXL ALGORITHM's own interpretation",
        "# statements. It is machine-generated. Records carry",
        "# label_provenance=ALGORITHM_PHILIPS_DXL so a model trained on the merged",
        "# cohort can be audited, or the source down-weighted, on that basis.",
        "# =====================================================================",
        "",
        "version: 1",
        "",
        "sources:",
        "  cuhk_stemi:",
        '    name: "CUHK STEMI registry (Philips Sierra ECG XML)"',
        "    label_type: philips_dxl_statement_codes",
        '    label_source: "<interpretations>/<unparsedstatement code=..> in each XML"',
        "",
        "    # An ACS/STEMI-registry cohort: a STEMI-negative record here is a",
        "    # different acute presentation, never a healthy control. As with the",
        "    # 2026 ACS/STEMI source, this dataset contributes NO NORMAL records.",
        "    normal_assertion: null",
        "    contributes_classes: [STEMI, AF, LVH]",
        "",
        "    unknown_code_policy:",
        "      status: EXCLUDE_UNKNOWN_CODE",
        "      disqualifies_normal: true",
        "",
        "    labels:",
    ]

    order = [b["name"] for b in buckets]
    for bucket_name in order:
        ds = by_bucket.get(bucket_name)
        if not ds:
            continue
        b = next(bb for bb in buckets if bb["name"] == bucket_name)
        n_rec = sum(d["n_records"] for d in ds)
        out += [
            "",
            f"      # ---- rule bucket {bucket_name}: {len(ds)} codes, "
            f"{n_rec} record-hits -> {b['status']}"
            + (f" -> {b['maps_to']}" if b.get("maps_to") else ""),
            block_scalar(b["reason"], "      # "),
        ]
        for d in ds:
            out.append(f"      {d['philips_code']}:")
            out.append(f"        maps_to: {d['maps_to'] or 'null'}")
            out.append(f"        status: {d['status']}")
            out.append(f"        disqualifies_normal: {d['disqualifies_normal']}")
            out.append(f"        n_records: {d['n_records']}")
            stmt = d["philips_statement"].replace('"', "'")[:150]
            out.append(f'        name: "{stmt}"')
            out.append(f"        reason: >")
            out.append(block_scalar(
                f"[rule bucket {bucket_name}] " + b["reason"], "          "))

    OUT_YAML.write_text("\n".join(out) + "\n", encoding="utf-8")

    print(f"wrote {OUT_CSV}  ({len(decisions)} codes)")
    print(f"wrote {OUT_YAML}")
    print("\nrule bucket summary:")
    print(f"  {'bucket':<12} {'codes':>6} {'record-hits':>12}  status")
    for name in order:
        ds = by_bucket.get(name)
        if not ds:
            continue
        b = next(bb for bb in buckets if bb["name"] == name)
        tgt = f" -> {b['maps_to']}" if b.get("maps_to") else ""
        print(f"  {name:<12} {len(ds):>6} {sum(d['n_records'] for d in ds):>12}"
              f"  {b['status']}{tgt}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
